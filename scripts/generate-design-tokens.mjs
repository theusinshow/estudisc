import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(repoRoot, "design-system", "design-tokens.json");
const outputPath = path.join(repoRoot, "src", "styles", "generated", "design-tokens.css");

function toKebab(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}

function resolveReferences(value, root) {
  if (typeof value !== "string") {
    return String(value);
  }

  return value.replace(/\{([^}]+)\}/g, (_match, tokenPath) => {
    const resolved = tokenPath.split(".").reduce((current, segment) => current?.[segment], root);

    if (resolved === undefined || typeof resolved === "object") {
      throw new Error(`Unable to resolve token reference: {${tokenPath}}`);
    }

    return resolveReferences(resolved, root);
  });
}

function collectTokens(node, root, prefix = []) {
  if (node === null || node === undefined) {
    return [];
  }

  if (Array.isArray(node)) {
    return [];
  }

  if (typeof node !== "object") {
    return [[`--estudisc-${prefix.map(toKebab).join("-")}`, resolveReferences(node, root)]];
  }

  return Object.entries(node)
    .filter(([key]) => !key.startsWith("$"))
    .flatMap(([key, value]) => collectTokens(value, root, [...prefix, key]));
}

export async function generateDesignTokenCss({ source = sourcePath, output = outputPath } = {}) {
  const raw = await readFile(source, "utf8");
  const tokens = JSON.parse(raw);
  const { themes = {}, ...rootTokens } = tokens;
  const entries = collectTokens(rootTokens, tokens).sort(([left], [right]) => left.localeCompare(right));
  const byName = ([left], [right]) => left.localeCompare(right);
  const block = (selector, list) => [`${selector} {`, ...list.map(([name, value]) => `  ${name}: ${value};`), "}"];
  // Themes (e.g. vibrante) override the same variables under an attribute, so a subtree or <html> can opt in.
  const themeBlocks = Object.entries(themes).flatMap(([themeName, theme]) => [
    ...block(`[data-theme="${themeName}"]`, collectTokens(theme.base ?? {}, tokens).sort(byName)),
    ...Object.entries(theme.palettes ?? {}).flatMap(([palette, overrides]) =>
      block(`[data-theme="${themeName}"][data-palette="${palette}"]`, collectTokens(overrides, tokens).sort(byName))
    )
  ]);

  const css = [
    "/*",
    " * GENERATED FILE. DO NOT EDIT MANUALLY.",
    " * Source: design-system/design-tokens.json",
    ` * Generated by: scripts/${path.basename(fileURLToPath(import.meta.url))}`,
    " */",
    ...block(":root", entries),
    ...themeBlocks,
    ""
  ].join("\n");

  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, css, "utf8");
  return { count: entries.length, output };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  generateDesignTokenCss()
    .then((result) => {
      console.log(`Generated ${result.count} design tokens at ${path.relative(repoRoot, result.output)}`);
    })
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
}
