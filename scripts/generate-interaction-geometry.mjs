import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const target = fileURLToPath(new URL('../src/styles/application/interaction-geometry.css', import.meta.url));
const rules = ['/* Generated by scripts/generate-interaction-geometry.mjs. Bounded geometry without CSP inline styles. */'];
for (let value = 0; value <= 100; value++) {
  rules.push(`.comparison-after[data-position="${value}"] { clip-path: inset(0 ${100 - value}% 0 0); }`);
  rules.push(`.location-marker[data-x="${value}"] { left: clamp(22px, ${value}%, calc(100% - 22px)); }`);
  rules.push(`.location-marker[data-y="${value}"] { top: clamp(22px, ${value}%, calc(100% - 22px)); }`);
}
for (let tick = 4; tick <= 12; tick++) rules.push(`.location-frame[data-zoom="${tick / 4}"] { width: ${tick * 25}%; }`);
const expected = rules.join('\n') + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== expected) throw Error('Interaction geometry CSS is stale');
  console.log('PASS: bounded interaction geometry CSS');
} else { writeFileSync(target, expected); console.log('Generated bounded interaction geometry CSS'); }
