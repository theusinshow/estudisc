import { readFileSync } from "node:fs";
import { expect, it } from "vitest";
import selection from "../../tools/estudisc-content-studio/teaching-complements/portuguese-reading-selection.json";
import languageSelection from "../../tools/estudisc-content-studio/teaching-complements/portuguese-language-selection.json";
import { loadBlueprintCorpus } from "../../tools/estudisc-content-studio/blueprint-sources";
import { createLessonBlueprint } from "../../tools/estudisc-content-studio/blueprint-policy";
import { createEnrichmentPreview } from "../../tools/estudisc-content-studio/enrichment";
import { predictionEnrichmentRecipeSchema } from "../../tools/estudisc-content-studio/enrichment-contracts";
import { hashCanonicalJson } from "@/lib/canonical-json";
import { lessonVersionPackSchema } from "@/features/import/application/lesson-version-contracts";
import { resolveLessonVersionContext } from "@/features/import/application/lesson-version-policy";

it.each([...selection.items, ...languageSelection.items])("preserves the source and truthful exploration for $lessonId", item => {
  const recipe = predictionEnrichmentRecipeSchema.parse(JSON.parse(readFileSync(`tools/estudisc-content-studio/recipes/reading-${item.lessonId.toLowerCase()}.v2.json`, "utf8")));
  const { pack } = loadBlueprintCorpus(process.cwd()).find(c => c.pack.track.id === recipe.identity.trackId)!;
  const moduleRecord = pack.track.modules.find(m => m.lessons.some(l => l.id === item.lessonId))!;
  const source = moduleRecord.lessons.find(l => l.id === item.lessonId)!;
  const before = hashCanonicalJson(pack);
  const blueprint = createLessonBlueprint(pack, moduleRecord.subjectCode, source, { corpusHash: before, dependencyHash: before, policyHash: before, assetHash: hashCanonicalJson([]) }, [], "2026-10-11T00:00:00Z");
  const preview = createEnrichmentPreview(pack, blueprint, recipe);
  const packet = lessonVersionPackSchema.parse({ schema: "caderno.lesson.v2", packId: `fixture.reading.${item.lessonId.toLowerCase()}`, version: 1, authorId: "fixture-author", target: { trackId: pack.track.id, trackVersion: pack.version, moduleId: moduleRecord.id, lessonId: source.id, baseVersion: source.version, baseHash: recipe.sourceLessonHash }, lesson: preview.lesson, questionReferences: preview.questionReferences });
  expect(() => resolveLessonVersionContext([pack], packet)).not.toThrow();
  expect(source.objectives).toEqual([]);
  expect(preview.lesson.objectives).toEqual([]);
  expect({ ...packet.lesson, status: source.status, version: source.version, blocks: packet.lesson.blocks.filter(b => b.id !== recipe.additions[0].newBlockId) }).toEqual(source);
  expect(preview.questionReferences).toHaveLength(8);
  const anchor = source.blocks.find(b => b.id === recipe.additions[0].beforeBlockId)!;
  const concept = source.concepts.find(c => c.id === recipe.additions[0].conceptId)!;
  expect(concept.title).toBe(item.conceptTitle);
  expect(anchor.conceptIds).toEqual([]);
  expect(preview.newBlocks[0].type).toBe("prediction");
  const payload = preview.newBlocks[0].payload;
  expect("content" in payload && payload.content).toContain("Objetivo proposto desta exploração:");
  expect(preview.newBlocks[0].payload).not.toHaveProperty("correctAnswer");
  expect(hashCanonicalJson(pack)).toBe(before);
  const unsupported = structuredClone(recipe);
  unsupported.additions[0].parameters.explanationQuote = "Esta explicação não existe no exemplo original preservado.";
  expect(() => createEnrichmentPreview(pack, blueprint, unsupported)).toThrow("quotes");
  const changedRef = structuredClone(packet);
  changedRef.questionReferences[0].hash = "0".repeat(64);
  expect(() => resolveLessonVersionContext([pack], changedRef)).toThrow("Question reference/hash changed");
});
